            end else begin
                modulated_out <= current_env; 
            end
        end
    end

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state             <= S_IDLE;
            us_clock_count    <= 32'd0;
            state_elapsed_us  <= 32'd0;
            pair_elapsed_us   <= 32'd0;
            env_phase         <= 32'd0;
        end else begin
            if (!enable) begin
                state            <= S_IDLE;
                us_clock_count   <= 32'd0;
                state_elapsed_us <= 32'd0;
                pair_elapsed_us  <= 32'd0;
                env_phase        <= 32'd0;
            end else begin
                if (us_tick) begin
                    us_clock_count <= 32'd0;
                    
                    if (pair_elapsed_us >= active_period_us - 1)
                        pair_elapsed_us <= 32'd0;
                    else
                        pair_elapsed_us <= pair_elapsed_us + 1'b1;

                    case (state)
                        S_IDLE: begin
                            state            <= S_PULSE_1;
                            state_elapsed_us <= 32'd0;
                            env_phase        <= 32'd0;
                        end
                        S_PULSE_1: begin
                            if (state_elapsed_us >= PULSE_WIDTH_US - 1) begin
                                state            <= S_GAP;
                                state_elapsed_us <= 32'd0;
                                env_phase        <= 32'd0;
                            end else begin
                                state_elapsed_us <= state_elapsed_us + 1'b1;
                            end
                        end
                        S_GAP: begin
                            if (state_elapsed_us >= INTER_PULSE_DELAY_US - 1) begin
                                state            <= S_PULSE_2;
                                state_elapsed_us <= 32'd0;
                                env_phase        <= 32'd0;
                            end else begin
                                state_elapsed_us <= state_elapsed_us + 1'b1;
                            end
                        end
                        S_PULSE_2: begin
                            if (state_elapsed_us >= PULSE_WIDTH_US - 1) begin
                                state            <= S_WAIT;
                                state_elapsed_us <= 32'd0;
                                env_phase        <= 32'd0;
                            end else begin
                                state_elapsed_us <= state_elapsed_us + 1'b1;
                            end
                        end
                        S_WAIT: begin
                            if (pair_elapsed_us >= active_period_us - 1) begin
                                state            <= S_PULSE_1;
                                state_elapsed_us <= 32'd0;
                                env_phase        <= 32'd0;
                            end
                        end
                        default: state <= S_IDLE;
                    endcase
                end else if (CLOCKS_PER_US > 1) begin
                    us_clock_count <= us_clock_count + 1'b1;
                end
                
                if (state == S_PULSE_1 || state == S_PULSE_2) begin
                    env_phase <= env_phase + ENV_PHASE_INC;
                end
            end
        end
    end
endmodule
